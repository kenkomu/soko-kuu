#!/usr/bin/env bash
# Deploy Soko Kuu contract to NEAR testnet with near-cli-rs 0.31.1. Keys are never written into the repo.
# Required env:
#   ACCOUNT        funded testnet parent account, e.g. sokokuu-ken.testnet
#   KEY_FILE       path to ACCOUNT's credentials JSON (outside the repo)
#   RELAYER_PUBKEY public key ed25519:... of the key the RUNNER will hold (generate it yourself, see DEPLOY.md)
# Optional env: SEED (default 1), WASM (default: optimised wasm, see DEPLOY.md), FUND_CONTRACT (6), FUND_RELAYER (2)
# DRY_RUN=1 prints the commands only. DRY_RUN=2 runs every command with --help appended (syntax check, changes nothing).
# The two new sub-accounts get autogenerated bootstrap keys saved by near-cli in ~/.near-credentials/testnet/ (outside the repo).
set -euo pipefail
: "${ACCOUNT:?set ACCOUNT}"; : "${KEY_FILE:?set KEY_FILE}"
SEED="${SEED:-1}"; DRY_RUN="${DRY_RUN:-0}"
HERE="$(cd "$(dirname "$0")" && pwd)"
WASM="${WASM:-$HERE/target/sokokuu_contract.opt.wasm}"
FUND_CONTRACT="${FUND_CONTRACT:-6}"; FUND_RELAYER="${FUND_RELAYER:-2}"
CONTRACT="sokokuu.$ACCOUNT"; RELAYER="relayer.$ACCOUNT"
NET=(network-config testnet)
SIGN_PARENT=(sign-with-access-key-file "$KEY_FILE" send)

[ -f "$KEY_FILE" ] || { echo "KEY_FILE not found"; exit 1; }
[ -f "$WASM" ] || { echo "build first, see DEPLOY.md"; exit 1; }
: "${RELAYER_PUBKEY:?set RELAYER_PUBKEY=ed25519:... (see DEPLOY.md step 2)}"
case "$RELAYER_PUBKEY" in ed25519:*) ;; *) echo "RELAYER_PUBKEY must start with ed25519:"; exit 1;; esac
[ "$DRY_RUN" != 0 ] || command -v near >/dev/null || { echo "near-cli-rs not installed"; exit 1; }

run() {
  echo "+ near $*"
  case "$DRY_RUN" in 0) near "$@";; 2) near "$@" --help >/dev/null && echo "  syntax ok";; esac
}
NEAR_BOOT="${HOME}/.near-credentials/testnet"

# 1. sub-accounts, created and funded by ACCOUNT (bootstrap keys go to near-cli's legacy keychain)
run account create-account fund-myself "$CONTRACT" "${FUND_CONTRACT} NEAR" autogenerate-new-keypair save-to-legacy-keychain sign-as "$ACCOUNT" "${NET[@]}" "${SIGN_PARENT[@]}"
run account create-account fund-myself "$RELAYER" "${FUND_RELAYER} NEAR" autogenerate-new-keypair save-to-legacy-keychain sign-as "$ACCOUNT" "${NET[@]}" "${SIGN_PARENT[@]}"
# 2. deploy: a contract account signs its own deploy. Then init as ACCOUNT so the OWNER (pause rights) is the parent account.
run contract deploy "$CONTRACT" use-file "$WASM" without-init-call "${NET[@]}" sign-with-legacy-keychain send
run contract call-function as-transaction "$CONTRACT" new json-args "{\"chain_id\":\"testnet\",\"seed\":$SEED,\"relayer\":\"$RELAYER\"}" prepaid-gas '30 Tgas' attached-deposit '0 NEAR' sign-as "$ACCOUNT" "${NET[@]}" "${SIGN_PARENT[@]}"
# 3. restricted relayer key: function-call only, receiver = contract, only these methods
run account add-key "$RELAYER" grant-function-call-access --allowance '1.8 NEAR' --contract-account-id "$CONTRACT" --function-names 'act,advance_clock,rebind_key' use-manually-provided-public-key "$RELAYER_PUBKEY" "${NET[@]}" sign-with-legacy-keychain send
# 4. remove the relayer's bootstrap full-access key so only the function-call key remains
if [ "$DRY_RUN" = 0 ]; then
  BOOT_PUB="$(python3 -c 'import json,sys;print(json.load(open(sys.argv[1]))["public_key"])' "$NEAR_BOOT/$RELAYER.json")"
else BOOT_PUB="ed25519:BOOTSTRAP_KEY"; fi
run account delete-keys "$RELAYER" public-keys "$BOOT_PUB" "${NET[@]}" sign-with-legacy-keychain send
# 5. checks
run contract call-function as-read-only "$CONTRACT" clock json-args '{}' "${NET[@]}" now
run account list-keys "$RELAYER" "${NET[@]}" now
echo "Done. Contract: $CONTRACT  Relayer: $RELAYER  Owner: $ACCOUNT"
